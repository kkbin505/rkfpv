#!/usr/bin/env python3
"""Render the OSD font into src/osd_font.h (run on the PC, needs Pillow).

    python3 tools/mkfont.py [font.ttf] > src/osd_font.h

Printable ASCII (32..126) from a monospaced TTF, two pixel sizes (720p and
1080p streams). Each glyph pixel is a 2-bit OSD code, ready to copy into a
2BPP overlay canvas:
    0 = transparent, 2 = outline (LUT 1, black), 3 = glyph (LUT 0, white)
The outline is the glyph grown by one pixel, so text stays readable on any
background. Default font: DejaVu Sans Mono Bold (Bitstream Vera license).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
SIZES = [("small", 20), ("large", 30)]   # pt for 720p, 1080p
FIRST, LAST = 32, 126


def render(px):
    font = ImageFont.truetype(FONT, px)
    asc, desc = font.getmetrics()
    adv = round(font.getlength("M"))
    w, h = adv + 2, asc + desc + 2          # +1 px outline on each side
    glyphs = []
    for c in range(FIRST, LAST + 1):
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((1, 1), chr(c), font=font, fill=255)
        fg = [[im.getpixel((x, y)) >= 128 for x in range(w)] for y in range(h)]
        cell = []
        for y in range(h):
            for x in range(w):
                if fg[y][x]:
                    cell.append(3)
                elif any(fg[yy][xx] for yy in range(max(0, y - 1), min(h, y + 2))
                         for xx in range(max(0, x - 1), min(w, x + 2))):
                    cell.append(2)
                else:
                    cell.append(0)
        glyphs.append(cell)
    return w, h, glyphs


def main():
    out = ["/* Generated by tools/mkfont.py from %s. Do not edit. */" % FONT.rsplit("/", 1)[-1],
           "/* Font: DejaVu Sans Mono (Bitstream Vera license), see THIRD_PARTY_NOTICES.md */",
           "#ifndef OSD_FONT_H", "#define OSD_FONT_H", "#include <stdint.h>", "",
           "typedef struct { int w, h, first, last; const uint8_t *data; } osd_font_t;", ""]
    for name, px in SIZES:
        w, h, glyphs = render(px)
        out.append("/* %d px: %dx%d cells, 0 transparent / 2 outline / 3 glyph */" % (px, w, h))
        out.append("static const uint8_t osd_font_%s_data[%d] = {" % (name, len(glyphs) * w * h))
        for i, cell in enumerate(glyphs):
            out.append("\t/* '%s' */ %s," % (chr(FIRST + i).replace("\\", "\\\\").replace("*", "x"),
                                             ",".join(str(v) for v in cell)))
        out.append("};")
        out.append("static const osd_font_t osd_font_%s = { %d, %d, %d, %d, osd_font_%s_data };"
                   % (name, w, h, FIRST, LAST, name))
        out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
